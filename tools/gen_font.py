CHARSET = (
    " !\"&'()*+,-./0123456789:;<=>?"
    "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
    "abcdefghijklmnopqrstuvwxyz"
    "áéíóúüñÁÉÍÓÚÜÑ¡¿…♪♥→×"
)


def build():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    glyphs = [G[ch] for ch in CHARSET]
    n = len(glyphs)

    # Tira: [variante oscura n glifos][variante clara n glifos]
    sheet = Canvas(8 * n * 2, 8)
    for var in range(2):
        for gi, rows in enumerate(glyphs):
            ox = (var * n + gi) * 8
            for y, row in enumerate(rows):
                for x, ch in enumerate(row):
                    if ch != '#':
                        continue
                    if var == 0:
                        sheet.set(ox + x, y, 'k')
                    else:
                        # clara: blanco con sombra abajo-derecha
                        sheet.set(ox + x, y, 'w')
        if var == 1:
            # sombras de la variante clara
            for gi, rows in enumerate(glyphs):
                ox = (var * n + gi) * 8
                for y, row in enumerate(rows):
                    for x, ch in enumerate(row):
                        if ch == '#':
                            if sheet.get(ox + x + 1, y + 1) == 0 and x < 7 and y < 7:
                                sheet.set(ox + x + 1, y + 1, 'K')

    save_png(os.path.join(root, 'assets/gfx/font.png'), sheet)

    # tabla codepoint -> índice
    entries = sorted((ord(ch), i) for i, ch in enumerate(CHARSET))
    with open(os.path.join(root, 'source/data/font_map.h'), 'w') as f:
        f.write("// Generado por tools/gen_font.py — NO editar a mano\n")
        f.write("#ifndef FONT_MAP_H__\n#define FONT_MAP_H__\n\n")
        f.write(f"#define FONT_NUM_GLYPHS {n}\n\n")
        f.write("typedef struct { unsigned short cp; unsigned short glyph; } FontMapEntry;\n\n")
        f.write(f"static const FontMapEntry font_map[{len(entries)}] = {{\n")
        for cp, i in entries:
            f.write(f"    {{ {cp}, {i} }},\n")
        f.write("};\n\n#endif\n")
    print(f"font: {n} glifos x2 variantes")


if __name__ == '__main__':
    build()
